import { test } from 'node:test'
import assert from 'node:assert/strict'
import { homedir } from 'node:os'

import { stripJsonc, translateServer, render, translateValue } from '../lib.mjs'

test('stripJsonc removes comments and trailing commas', () => {
  const src = `{
    // line comment
    "a": 1, /* block
    comment */
    "b": [1, 2, 3,],
  }`
  const parsed = JSON.parse(stripJsonc(src))
  assert.deepEqual(parsed, { a: 1, b: [1, 2, 3] })
})

test('stripJsonc leaves URLs and quoted // alone', () => {
  const src = `{ "url": "https://example.com/a//b", "s": "//not a comment" }`
  const parsed = JSON.parse(stripJsonc(src))
  assert.equal(parsed.url, 'https://example.com/a//b')
  assert.equal(parsed.s, '//not a comment')
})

test('translateValue: {env:NAME} exact form', () => {
  assert.deepEqual(translateValue('{env:FOO}'), {
    raw: '!!js (process.env.FOO || "")',
  })
})

test('translateValue: bearer header form', () => {
  const { raw } = translateValue('Bearer {env:TOKEN}')
  assert.ok(raw.includes('!!js'))
  assert.ok(raw.includes('${process.env.TOKEN || ""}'))
})

test('translateValue: home path is made portable', () => {
  const { raw } = translateValue(homedir() + '/.local/bin/x')
  assert.ok(raw.includes('${process.env.HOME}'))
  assert.ok(!raw.includes(homedir()))
})

test('remote server -> streamable-http', () => {
  const e = translateServer('context7', {
    type: 'remote',
    url: 'https://mcp.context7.com/mcp',
    headers: { Authorization: 'Bearer {env:CONTEXT7_API_KEY}' },
    enabled: true,
  }, { failOnStartupError: ['context7'] })
  assert.equal(e.config.transport, 'streamable-http')
  assert.equal(e.config.url.plain, 'https://mcp.context7.com/mcp')
  assert.ok(e.config.headers.Authorization.raw.startsWith('!!js'))
  assert.equal(e.config.failOnStartupError, true)
  assert.equal(e.disabled, undefined)
})

test('local server -> stdio, env -C collapses to cwd', () => {
  const e = translateServer('freecad', {
    type: 'local',
    command: ['/usr/bin/env', '-C', '/tmp/opencode', homedir() + '/miniconda3/bin/freecad-mcp'],
    environment: { FREECAD_XMLRPC_PORT: '9875' },
    enabled: false,
  })
  assert.equal(e.config.transport, 'stdio')
  assert.ok(e.config.command.raw.startsWith('!!js'))
  assert.equal(e.config.cwd.plain, '/tmp/opencode')
  assert.equal(e.config.env.FREECAD_XMLRPC_PORT.plain, '9875')
  assert.equal(e.disabled, true)
})

test('forced disable adds reason comment and disabled flag', () => {
  const e = translateServer('sentry', {
    type: 'remote',
    url: 'https://mcp.sentry.dev/mcp',
    enabled: true,
  }, { disabled: { sentry: 'kept disabled' } })
  assert.equal(e.disabled, true)
  assert.equal(e.reason, 'kept disabled')
})

test('extra merges config additions not present in opencode', () => {
  const e = translateServer('solidcraft', {
    type: 'local',
    command: [homedir() + '/.local/bin/solidcraft-cli', 'mcp', '--allow-any-path'],
    enabled: true,
  }, { extra: { solidcraft: { cwd: homedir() + '/Documents/SolidCraft' } } })
  assert.ok(e.config.cwd.raw.startsWith('!!js'))
  assert.deepEqual(e.config.args.map((a) => a.plain), ['mcp', '--allow-any-path'])
})

test('render emits valid-looking patch with insert list', () => {
  const e = translateServer('context7', {
    type: 'remote',
    url: 'https://mcp.context7.com/mcp',
    enabled: true,
  })
  const yaml = render([e])
  assert.ok(yaml.startsWith('# Generated by generate.mjs'))
  assert.ok(yaml.includes('- insert:'))
  assert.ok(yaml.includes('id: mcp-context7'))
  assert.ok(yaml.includes("name: '@deepseek-ai/dsh-mcp-client'"))
})
